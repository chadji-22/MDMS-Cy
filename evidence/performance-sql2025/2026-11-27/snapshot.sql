SET NOCOUNT ON;
DECLARE @sql NVARCHAR(MAX) = N'';
SELECT @sql = @sql + N'SELECT ''' + t.name + N''' AS tbl, COUNT_BIG(*) AS n, CHECKSUM_AGG(BINARY_CHECKSUM(*)) AS chk FROM dbo.' + QUOTENAME(t.name) + N' UNION ALL '
FROM sys.tables t WHERE t.name IN ('ROLE','ORGANIZATION','USER_ACCOUNT','TECHNICIAN_AVAILABILITY','TRANSFORMER','PREMISE','METER_TYPE','METER','DOCUMENT','OBIS_CODE','TELEMETRY_PACKET','METER_READING','TRANSFORMER_READING','AGGREGATE','TRANSFORMER_CURRENT_STATE','EVENT','NOTIFICATION','SERVICE_TYPE','WORK_ORDER','REMOTE_COMMAND','TARIFF','BILL','PAYMENT','GDPR_REQUEST','AUDIT_LOG')
ORDER BY t.name;
SET @sql = LEFT(@sql, LEN(@sql) - 10) + N' ORDER BY tbl';
EXEC sp_executesql @sql;
SELECT name, type_desc, CAST(size/128.0 AS DECIMAL(9,2)) size_mb, CAST(FILEPROPERTY(name,'SpaceUsed')/128.0 AS DECIMAL(9,2)) used_mb FROM sys.database_files;
